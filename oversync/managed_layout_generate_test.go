package oversync

import (
	"bytes"
	"context"
	"fmt"
	"log/slog"
	"os"
	"sort"
	"strings"
	"testing"

	"github.com/jackc/pgx/v5"
	"github.com/stretchr/testify/require"
)

// TestGenerateManagedLayoutManifest is the owner workflow for the compiled
// static manifest. Run explicitly with OVERSYNC_GENERATE_MANAGED_LAYOUT=1.
func TestGenerateManagedLayoutManifest(t *testing.T) {
	if os.Getenv("OVERSYNC_GENERATE_MANAGED_LAYOUT") != "1" {
		t.Skip("generator")
	}
	ctx := context.Background()
	pool := newIntegrationTestPool(t, ctx)
	service := &SyncService{logger: slog.Default(), config: &ServiceConfig{}}
	require.NoError(t, normalizeHistoryProjectionConfig(service.config))
	require.NoError(t, pgx.BeginTxFunc(ctx, pool, syncMutationTxOptions(), func(tx pgx.Tx) error { return service.createFreshSyncLayoutInTx(ctx, tx) }))
	facts, err := loadManagedLayoutFacts(ctx, pool)
	require.NoError(t, err)
	retryKeys := map[managedLayoutFactKey]struct{}{}
	for _, fact := range append(append([]managedLayoutFact(nil), retryableWriteManagedLayoutFacts...), pushOutcomeManagedLayoutFacts...) {
		retryKeys[managedLayoutFactKey{fact.Kind, fact.Identity, fact.Attribute}] = struct{}{}
	}
	static := facts[:0]
	for _, fact := range facts {
		if _, ok := retryKeys[managedLayoutFactKey{fact.Kind, fact.Identity, fact.Attribute}]; !ok {
			static = append(static, fact)
		}
	}
	sort.Slice(static, func(i, j int) bool { return managedLayoutFactLess(static[i], static[j]) })
	var generated bytes.Buffer
	generated.WriteString("var expectedManagedLayoutFactsByName = map[string][]managedLayoutFact{\n\tsyncSchemaLayoutName: {\n")
	for _, fact := range static {
		fmt.Fprintf(&generated, "\t\t{Kind: %q, Identity: %q, Attribute: %q, Value: %q},\n", fact.Kind, fact.Identity, fact.Attribute, fact.Value)
	}
	generated.WriteString("\t},\n}\n")
	path := "managed_layout.go"
	source, err := os.ReadFile(path)
	require.NoError(t, err)
	start := bytes.Index(source, []byte("var expectedManagedLayoutFactsByName ="))
	require.NotEqual(t, -1, start)
	endMarker := []byte("\ntype registeredTableTriggerTargetInventoryRow struct")
	end := bytes.Index(source, endMarker)
	require.NotEqual(t, -1, end)
	updated := append(append(append([]byte(nil), source[:start]...), generated.Bytes()...), source[end:]...)
	updated = []byte(strings.ReplaceAll(string(updated), "\r\n", "\n"))
	require.NoError(t, os.WriteFile(path, updated, 0o644))
}
